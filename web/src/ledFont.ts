export const FONT_HEIGHT = 5;

/** The text as five rows of LEDs (1 lit, 0 unlit), one blank LED column between letters. */
export function textLeds(text: string): number[][] {
  const rows: number[][] = [];
  for (let r = 0; r < FONT_HEIGHT; r += 1) {
    rows.push([]);
  }
  const letters = text.toUpperCase();
  for (let i = 0; i < letters.length; i += 1) {
    let glyph = GLYPHS[letters[i]];
    if (glyph === undefined) {
      glyph = GLYPHS[" "];
    }
    for (let r = 0; r < FONT_HEIGHT; r += 1) {
      if (i > 0) {
        rows[r].push(0);
      }
      for (let c = 0; c < glyph[r].length; c += 1) {
        if (glyph[r][c] === "#") {
          rows[r].push(1);
        } else {
          rows[r].push(0);
        }
      }
    }
  }
  return rows;
}
